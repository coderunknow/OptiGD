#!/usr/bin/env python3
"""
OptiGD diagnostics JSON schema validator.

Validates the JSON report produced by
`DiagnosticsEngine::generateJsonReport()` / `exportJsonReportToFile()`
(the same file the mod writes to
`<GD save dir>/geode/mods/coderunknow.optigd/optigd_diagnostics.json`
when `export-diagnostics-on-exit` is enabled).

The report is generated by hand-rolled string concatenation, so this script
exists to guarantee the produced artefact is actually parseable and that the
fields documented in docs/BENCHMARKS.md are present and of the expected type.

Usage:
    python3 tools/validate_diagnostics_json.py optigd_diagnostics.json
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

SCHEMA = {
    "optigd_version": str,
    "gd_version": str,
    "geode_version": str,
    "platform": dict,
    "configuration": dict,
    "telemetry": dict,
    "notes": dict,
    "fallbacks": list,
}

PLATFORM_SCHEMA = {
    "os": str,
    "compiler": str,
    "cores": int,
    "total_ram_mb": int,
}

CONFIGURATION_SCHEMA = {
    "active_tier": str,
    "target_fps": (int, float),
    "particle_density_scale": (int, float),
    "max_active_particles": int,
    "cull_offscreen_emitters": bool,
    "spatial_culling_enabled": bool,
    "particle_throttling_enabled": bool,
    "trigger_indexing_enabled": bool,
    "matrix_caching_enabled": bool,
    "adaptive_governor_enabled": bool,
}

TELEMETRY_SCHEMA = {
    "total_frames": int,
    "avg_fps": (int, float),
    "min_fps": (int, float),
    "max_fps": (int, float),
    "avg_frame_time_ms": (int, float),
    "median_frame_time_ms": (int, float),
    "p95_frame_time_ms": (int, float),
    "p99_frame_time_ms": (int, float),
    "avg_update_cpu_time_ms": (int, float),
    "avg_optigd_overhead_us": (int, float),
    "total_objects_culled": int,
    "total_particles_avoided": int,
    "total_triggers_skipped": int,
    "total_matrix_cache_hits": int,
    "total_matrix_cache_misses": int,
    "peak_arena_bytes": int,
    "total_arena_allocations": int,
    "total_heap_allocations_avoided": int,
    "tier_transitions_count": int,
}

FALLBACK_SCHEMA = {
    "frame": int,
    "feature": str,
    "reason": str,
    "action": str,
}

NOTES_SCHEMA = {
    "native_trigger_execution_modified": bool,
    "total_triggers_skipped_meaning": str,
}


def check_section(data, schema, section, errors, path=""):
    if not isinstance(data, dict):
        errors.append("%s%s must be an object (got %s)"
                      % (path, section, type(data).__name__))
        return
    for key, expected in schema.items():
        if key not in data:
            errors.append("%s%s.%s is missing" % (path, section, key))
            continue
        if not isinstance(data[key], expected):
            errors.append("%s%s.%s has type %s, expected %s"
                          % (path, section, key, type(data[key]).__name__,
                             getattr(expected, "__name__", expected)))


def validate(doc) -> list:
    errors: list = []
    if not isinstance(doc, dict):
        return ["report root must be a JSON object"]

    for key, expected in SCHEMA.items():
        if key not in doc:
            errors.append("top level key '%s' is missing" % key)
        elif not isinstance(doc[key], expected):
            errors.append("top level key '%s' has type %s, expected %s"
                          % (key, type(doc[key]).__name__,
                             getattr(expected, "__name__", expected)))

    if errors:
        return errors

    check_section(doc["platform"], PLATFORM_SCHEMA, "platform", errors)
    check_section(doc["configuration"], CONFIGURATION_SCHEMA, "configuration", errors)
    check_section(doc["telemetry"], TELEMETRY_SCHEMA, "telemetry", errors)
    check_section(doc["notes"], NOTES_SCHEMA, "notes", errors)

    for i, fb in enumerate(doc["fallbacks"]):
        check_section(fb, FALLBACK_SCHEMA, "fallbacks", errors,
                      path="fallbacks[%d]." % i)

    # Semantic sanity: invalid measurements must not masquerade as valid.
    tel = doc["telemetry"]
    if tel["total_frames"] == 0 and (tel["avg_fps"] != 0 or tel["avg_frame_time_ms"] != 0):
        errors.append("telemetry reports fps/frame-time with total_frames == 0")
    for key in ("avg_frame_time_ms", "median_frame_time_ms",
                "p95_frame_time_ms", "p99_frame_time_ms",
                "avg_update_cpu_time_ms", "avg_optigd_overhead_us"):
        if tel[key] < 0:
            errors.append("telemetry.%s is negative (%s)" % (key, tel[key]))
    if tel["p95_frame_time_ms"] < tel["median_frame_time_ms"]:
        errors.append("telemetry P95 is below the median (percentiles are unsorted)")
    if tel["p99_frame_time_ms"] < tel["p95_frame_time_ms"]:
        errors.append("telemetry P99 is below P95 (percentiles are unsorted)")

    if doc["notes"]["native_trigger_execution_modified"]:
        errors.append("notes.native_trigger_execution_modified must remain false: "
                      "OptiGD must never replace native GD trigger execution")

    return errors


def main(argv):
    if len(argv) < 2:
        print("Usage: python3 tools/validate_diagnostics_json.py <report.json>")
        return 2

    path = Path(argv[1])
    if not path.exists():
        print("FAIL: report not found: %s" % path)
        return 2

    try:
        doc = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        print("FAIL: %s is not valid JSON: %s" % (path, exc))
        return 1

    errors = validate(doc)
    print("OptiGD diagnostics JSON schema validation")
    print("  file      : %s" % path)
    for e in errors:
        print("  [ERROR] %s" % e)
    print("  result    : %s" % ("FAIL" if errors else "PASS"))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
