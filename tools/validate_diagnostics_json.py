#!/usr/bin/env python3
"""
OptiGD diagnostics JSON schema validator.

Validates the JSON report produced by
`DiagnosticsEngine::generateJsonReport()` / `exportJsonReportToFile()`
(the same file the mod writes to
`<GD save dir>/geode/mods/coderunknow.optigd/optigd_diagnostics.json`
when `export-diagnostics-on-exit` is enabled).

The report is generated by hand-rolled string concatenation, so this script
exists to guarantee the produced artefact is actually parseable and that the
fields documented in docs/BENCHMARKS.md are present and of the expected type.

Two schema versions are accepted:

  * **v1** - no `report_schema_version` key. The beta.2 shape. Still validated, so
    an older report on disk remains readable and checkable.
  * **v2** - `report_schema_version == 2` (beta.3). Adds the window disclosure that
    makes the report interpretable at all: how many samples the percentiles came
    from, the capacity they were truncated at, whether they are exact or
    histogram-approximate, how many frames were excluded (stalls) or paused, and
    thread CPU time kept apart from the wall-clock span of the update call. A v2
    report missing any of that is a failure, because the point of the keys is that
    a reader can see the window a number describes.

Every v1 key is retained in v2, so this script never accepts a report that lost a
field it used to have.

Usage:
    python3 tools/validate_diagnostics_json.py optigd_diagnostics.json
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

SCHEMA_VERSION = 2
EXPECTED_CLASSIFICATION = "[INTERNAL-TELEMETRY]"
PERCENTILE_METHODS = ("exact", "histogram_approximate", "none")

SCHEMA = {
    "optigd_version": str,
    "gd_version": str,
    "geode_version": str,
    "evidence_classification": str,
    "platform": dict,
    "configuration": dict,
    "telemetry": dict,
    "notes": dict,
    "fallbacks": list,
}

PLATFORM_SCHEMA = {
    "os": str,
    "compiler": str,
    "cores": int,
    "total_ram_mb": int,
}

# v2 only: the report must say what machine produced it, not just what OS.
PLATFORM_SCHEMA_V2 = {
    "architecture": str,
}

# v2 only: the measurement window itself.
CAPTURE_SCHEMA = {
    "started_utc": str,
    "started_epoch_ms": int,
    "wall_duration_ms": (int, float),
    "active_duration_ms": (int, float),
    "level_resets": int,
    "scope": str,
}

CONFIGURATION_SCHEMA = {
    "active_tier": str,
    "target_fps": (int, float),
    "particle_density_scale": (int, float),
    "max_active_particles": int,
    "cull_offscreen_emitters": bool,
    "spatial_culling_enabled": bool,
    "particle_throttling_enabled": bool,
    "trigger_indexing_enabled": bool,
    "matrix_caching_enabled": bool,
    "adaptive_governor_enabled": bool,
}

# v2 only: window disclosure, exclusion accounting and thread CPU time.
TELEMETRY_SCHEMA_V2 = {
    "sample_count": int,
    "sample_window_ms": (int, float),
    "history_capacity": int,
    "history_truncated": bool,
    "percentile_method": str,
    "rejected_samples": int,
    "excluded_samples": int,
    "excluded_time_ms": (int, float),
    "stall_frames": int,
    "paused_frames": int,
    "hitch_frames": int,
    "hitch_total_ms": (int, float),
    "min_frame_time_ms": (int, float),
    "max_frame_time_ms": (int, float),
    "stddev_frame_time_ms": (int, float),
    "fps_from_window": (int, float),
    "avg_update_thread_cpu_time_ms": (int, float),
    "thread_cpu_time_available": bool,
    "avg_culling_us": (int, float),
    "avg_particle_us": (int, float),
    "avg_trigger_us": (int, float),
    "avg_matrix_us": (int, float),
    "avg_governor_us": (int, float),
    "window_owned_bytes": int,
}

NOTES_SCHEMA_V2 = {
    "avg_fps_meaning": str,
    "min_max_fps_meaning": str,
    "total_frames_meaning": str,
    "sample_count_meaning": str,
    "percentile_definition": str,
    "stall_frames_meaning": str,
    "paused_frames_meaning": str,
    "avg_update_cpu_time_ms_meaning": str,
    "avg_optigd_overhead_us_meaning": str,
    "non_finite_values_sanitized": bool,
}

TELEMETRY_SCHEMA = {
    "total_frames": int,
    "avg_fps": (int, float),
    "min_fps": (int, float),
    "max_fps": (int, float),
    "avg_frame_time_ms": (int, float),
    "median_frame_time_ms": (int, float),
    "p95_frame_time_ms": (int, float),
    "p99_frame_time_ms": (int, float),
    "avg_update_cpu_time_ms": (int, float),
    "avg_optigd_overhead_us": (int, float),
    "total_objects_culled": int,
    "total_particles_avoided": int,
    "total_triggers_skipped": int,
    "total_matrix_cache_hits": int,
    "total_matrix_cache_misses": int,
    "peak_arena_bytes": int,
    "total_arena_allocations": int,
    "total_heap_allocations_avoided": int,
    "tier_transitions_count": int,
}

FALLBACK_SCHEMA = {
    "frame": int,
    "feature": str,
    "reason": str,
    "action": str,
}

NOTES_SCHEMA = {
    "native_trigger_execution_modified": bool,
    "total_triggers_skipped_meaning": str,
}


# Keys whose value must be a non-empty string: an empty label passes a type check
# while telling the reader nothing, which for `architecture` or `scope` is the same
# as omitting the disclosure.
NON_EMPTY_STRINGS = (
    ("platform", "os"),
    ("platform", "architecture"),
    ("platform", "compiler"),
    ("configuration", "active_tier"),
    ("capture", "scope"),
)


def check_non_empty(doc, errors):
    for section, key in NON_EMPTY_STRINGS:
        value = doc.get(section, {}).get(key) if isinstance(doc.get(section), dict) else None
        if value is None:
            continue  # presence and type are the schema check's job
        if not isinstance(value, str) or not value.strip():
            errors.append("%s.%s must be a non-empty string (got %r)"
                          % (section, key, value))


def check_section(data, schema, section, errors, path=""):
    if not isinstance(data, dict):
        errors.append("%s%s must be an object (got %s)"
                      % (path, section, type(data).__name__))
        return
    for key, expected in schema.items():
        if key not in data:
            errors.append("%s%s.%s is missing" % (path, section, key))
            continue
        if not isinstance(data[key], expected):
            errors.append("%s%s.%s has type %s, expected %s"
                          % (path, section, key, type(data[key]).__name__,
                             getattr(expected, "__name__", expected)))


def validate(doc) -> list:
    errors: list = []
    if not isinstance(doc, dict):
        return ["report root must be a JSON object"]

    for key, expected in SCHEMA.items():
        if key not in doc:
            errors.append("top level key '%s' is missing" % key)
        elif not isinstance(doc[key], expected):
            errors.append("top level key '%s' has type %s, expected %s"
                          % (key, type(doc[key]).__name__,
                             getattr(expected, "__name__", expected)))

    if errors:
        return errors

    check_section(doc["platform"], PLATFORM_SCHEMA, "platform", errors)
    check_section(doc["configuration"], CONFIGURATION_SCHEMA, "configuration", errors)
    check_section(doc["telemetry"], TELEMETRY_SCHEMA, "telemetry", errors)
    check_section(doc["notes"], NOTES_SCHEMA, "notes", errors)

    for i, fb in enumerate(doc["fallbacks"]):
        check_section(fb, FALLBACK_SCHEMA, "fallbacks", errors,
                      path="fallbacks[%d]." % i)

    # Semantic sanity: invalid measurements must not masquerade as valid.
    tel = doc["telemetry"]
    if tel["total_frames"] == 0 and (tel["avg_fps"] != 0 or tel["avg_frame_time_ms"] != 0):
        errors.append("telemetry reports fps/frame-time with total_frames == 0")
    for key in ("avg_frame_time_ms", "median_frame_time_ms",
                "p95_frame_time_ms", "p99_frame_time_ms",
                "avg_update_cpu_time_ms", "avg_optigd_overhead_us"):
        if tel[key] < 0:
            errors.append("telemetry.%s is negative (%s)" % (key, tel[key]))
    if tel["p95_frame_time_ms"] < tel["median_frame_time_ms"]:
        errors.append("telemetry P95 is below the median (percentiles are unsorted)")
    if tel["p99_frame_time_ms"] < tel["p95_frame_time_ms"]:
        errors.append("telemetry P99 is below P95 (percentiles are unsorted)")

    if doc["notes"]["native_trigger_execution_modified"]:
        errors.append("notes.native_trigger_execution_modified must remain false: "
                      "OptiGD must never replace native GD trigger execution")

    if doc["evidence_classification"] != EXPECTED_CLASSIFICATION:
        errors.append("evidence_classification must be '%s' (got '%s'): this report "
                      "is OptiGD's own instrumentation, not an external capture"
                      % (EXPECTED_CLASSIFICATION, doc["evidence_classification"]))

    check_non_empty(doc, errors)
    errors.extend(validate_v2(doc))
    return errors


def validate_v2(doc) -> list:
    """Window-disclosure checks. Skipped for a v1 report (key absent)."""
    errors: list = []
    if "report_schema_version" not in doc:
        return errors

    version = doc["report_schema_version"]
    if version != SCHEMA_VERSION:
        return ["report_schema_version is %r, expected %d (a report from a newer "
                "OptiGD must not be silently reinterpreted)" % (version, SCHEMA_VERSION)]

    check_section(doc["platform"], PLATFORM_SCHEMA_V2, "platform", errors)
    check_section(doc.get("capture", {}), CAPTURE_SCHEMA, "capture", errors)
    check_section(doc["telemetry"], TELEMETRY_SCHEMA_V2, "telemetry", errors)
    check_section(doc["notes"], NOTES_SCHEMA_V2, "notes", errors)
    if errors:
        return errors

    tel = doc["telemetry"]
    cap = doc["capture"]
    notes = doc["notes"]

    # --- the window a percentile came from must be stated and consistent -------
    if tel["percentile_method"] not in PERCENTILE_METHODS:
        errors.append("telemetry.percentile_method '%s' is not one of %s"
                      % (tel["percentile_method"], ", ".join(PERCENTILE_METHODS)))
    if tel["sample_count"] > tel["total_frames"]:
        errors.append("sample_count %d exceeds total_frames %d: the percentiles "
                      "claim more samples than were offered"
                      % (tel["sample_count"], tel["total_frames"]))
    if tel["history_capacity"] <= 0:
        errors.append("history_capacity must be positive")
    if tel["sample_count"] > tel["history_capacity"]:
        errors.append("sample_count %d exceeds history_capacity %d"
                      % (tel["sample_count"], tel["history_capacity"]))
    if tel["history_truncated"] != (tel["total_frames"] > tel["history_capacity"]):
        errors.append("history_truncated is %s but total_frames %d vs capacity %d says %s"
                      % (tel["history_truncated"], tel["total_frames"],
                         tel["history_capacity"],
                         tel["total_frames"] > tel["history_capacity"]))
    if tel["percentile_method"] == "exact" and tel["history_truncated"]:
        errors.append("percentile_method 'exact' contradicts history_truncated: a "
                      "truncated history can only give approximate percentiles")
    if tel["percentile_method"] == "histogram_approximate" and not tel["history_truncated"]:
        errors.append("percentile_method 'histogram_approximate' with a complete "
                      "history: an approximation must be justified by an overflow")

    # --- every offered frame is accounted for exactly once ---------------------
    accounted = tel["sample_count"] + tel["excluded_samples"] + tel["rejected_samples"]
    if accounted != tel["total_frames"]:
        errors.append("frame budget does not add up: sample_count %d + excluded %d + "
                      "rejected %d = %d, but total_frames is %d"
                      % (tel["sample_count"], tel["excluded_samples"],
                         tel["rejected_samples"], accounted, tel["total_frames"]))
    if tel["stall_frames"] + tel["paused_frames"] > tel["excluded_samples"]:
        errors.append("stall_frames %d + paused_frames %d exceeds excluded_samples %d: "
                      "stalls and pauses are the reasons frames get excluded"
                      % (tel["stall_frames"], tel["paused_frames"],
                         tel["excluded_samples"]))

    # --- window length vs. sample count ----------------------------------------
    if tel["sample_count"] > 0:
        expected_window = tel["avg_frame_time_ms"] * tel["sample_count"]
        if abs(tel["sample_window_ms"] - expected_window) > max(1.0, expected_window * 0.02):
            errors.append("sample_window_ms %.3f disagrees with avg_frame_time_ms * "
                          "sample_count = %.3f"
                          % (tel["sample_window_ms"], expected_window))
    elif tel["sample_window_ms"] != 0:
        errors.append("sample_window_ms must be 0 when no sample was counted")

    # --- statistics -------------------------------------------------------------
    ordered = [("min_frame_time_ms", tel["min_frame_time_ms"]),
               ("median_frame_time_ms", tel["median_frame_time_ms"]),
               ("p95_frame_time_ms", tel["p95_frame_time_ms"]),
               ("p99_frame_time_ms", tel["p99_frame_time_ms"]),
               ("max_frame_time_ms", tel["max_frame_time_ms"])]
    for (lo_name, lo), (hi_name, hi) in zip(ordered, ordered[1:]):
        if hi < lo - 1e-9:
            errors.append("telemetry.%s (%.4f) is below %s (%.4f): percentiles are "
                          "out of order" % (hi_name, hi, lo_name, lo))
    for key in ("min_frame_time_ms", "max_frame_time_ms", "stddev_frame_time_ms",
                "hitch_total_ms", "excluded_time_ms", "sample_window_ms",
                "avg_update_thread_cpu_time_ms", "fps_from_window"):
        if tel[key] < 0:
            errors.append("telemetry.%s is negative (%s)" % (key, tel[key]))
    if tel["sample_count"] > 0 and tel["avg_frame_time_ms"] > 0:
        implied = 1000.0 / tel["avg_frame_time_ms"]
        if abs(tel["avg_fps"] - implied) > max(0.5, implied * 0.02):
            errors.append("avg_fps %.3f is inconsistent with avg_frame_time_ms %.3f "
                          "(implies %.3f)" % (tel["avg_fps"], tel["avg_frame_time_ms"], implied))
        if tel["max_frame_time_ms"] > 0:
            implied_min_fps = 1000.0 / tel["max_frame_time_ms"]
            if abs(tel["min_fps"] - implied_min_fps) > max(0.5, implied_min_fps * 0.02):
                errors.append("min_fps %.3f is inconsistent with max_frame_time_ms %.3f"
                              % (tel["min_fps"], tel["max_frame_time_ms"]))
        if tel["min_frame_time_ms"] > 0:
            implied_max_fps = 1000.0 / tel["min_frame_time_ms"]
            if abs(tel["max_fps"] - implied_max_fps) > max(0.5, implied_max_fps * 0.02):
                errors.append("max_fps %.3f is inconsistent with min_frame_time_ms %.3f"
                              % (tel["max_fps"], tel["min_frame_time_ms"]))

    # --- thread CPU time is a separate measurement, not a second opinion -------
    if not tel["thread_cpu_time_available"] and tel["avg_update_thread_cpu_time_ms"] != 0:
        errors.append("avg_update_thread_cpu_time_ms must be 0 when "
                      "thread_cpu_time_available is false: a value the platform "
                      "cannot supply must not be invented")
    if tel["thread_cpu_time_available"] and \
            tel["avg_update_thread_cpu_time_ms"] > tel["avg_update_cpu_time_ms"] * 1.05 + 0.05:
        errors.append("thread CPU time %.3f ms exceeds the wall-clock span of the same "
                      "call %.3f ms" % (tel["avg_update_thread_cpu_time_ms"],
                                        tel["avg_update_cpu_time_ms"]))

    # --- non-finite sanitization must be disclosed, not silent ------------------
    if not isinstance(notes["non_finite_values_sanitized"], bool):
        errors.append("notes.non_finite_values_sanitized must be a bool")
    if not notes["percentile_definition"].strip():
        errors.append("notes.percentile_definition must state the estimator used")
    if "nearest-rank" not in notes["percentile_definition"].lower() and \
            "nearest rank" not in notes["percentile_definition"].lower():
        errors.append("notes.percentile_definition must name the estimator "
                      "(nearest-rank), not just list the percentiles")

    # --- capture window ----------------------------------------------------------
    if cap["level_resets"] < 0:
        errors.append("capture.level_resets is negative")
    for key in ("wall_duration_ms", "active_duration_ms"):
        if cap[key] < 0:
            errors.append("capture.%s is negative" % key)
    if not cap["scope"].strip():
        errors.append("capture.scope must say what the window covers")
    # NOTE: `active_duration_ms <= wall_duration_ms` is deliberately NOT asserted
    # here. This report is also emitted by `optigd_tests --emit-report`, which feeds
    # synthetic frame intervals while the wall clock is real, so active time
    # legitimately exceeds it in that artifact. The ordering IS enforced for
    # benchmark sessions (tools/validate_benchmark_session_json.py), where both
    # numbers come from the same clock.
    return errors


def main(argv):
    if len(argv) < 2:
        print("Usage: python3 tools/validate_diagnostics_json.py <report.json>")
        return 2

    path = Path(argv[1])
    if not path.exists():
        print("FAIL: report not found: %s" % path)
        return 2

    try:
        doc = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        print("FAIL: %s is not valid JSON: %s" % (path, exc))
        return 1

    errors = validate(doc)
    print("OptiGD diagnostics JSON schema validation")
    print("  file      : %s" % path)
    print("  schema    : v%s" % doc.get("report_schema_version", 1)
          if isinstance(doc, dict) else "  schema    : ?")
    for e in errors:
        print("  [ERROR] %s" % e)
    print("  result    : %s" % ("FAIL" if errors else "PASS"))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
